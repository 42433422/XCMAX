import { beforeEach, expect, it, vi } from 'vitest'
const { addCollection } = vi.hoisted(() => ({ addCollection: vi.fn() }))
vi.mock('@iconify/vue', () => ({ addCollection }))
vi.mock('@iconify-json/vscode-icons/icons.json', () => ({ default: { prefix: 'vscode-icons', icons: {} } }))
beforeEach(() => { vi.resetModules(); addCollection.mockReset() })
it('deduplicates simultaneous loads and reuses a registered collection', async () => {
  addCollection.mockReturnValue(true)
  const { ensureFileTypeIcons } = await import('./fileTypeIcon')
  const first = ensureFileTypeIcons()
  expect(ensureFileTypeIcons()).toBe(first)
  await expect(first).resolves.toBe(true)
  await expect(ensureFileTypeIcons()).resolves.toBe(true)
  expect(addCollection).toHaveBeenCalledTimes(1)
})
it.each(['throw', 'false'])('allows a later load after registration returns %s', async failure => {
  if (failure === 'throw') addCollection.mockImplementationOnce(() => { throw new Error('chunk registration failed') })
  else addCollection.mockReturnValueOnce(false)
  addCollection.mockReturnValueOnce(true)
  const { ensureFileTypeIcons } = await import('./fileTypeIcon')
  await expect(ensureFileTypeIcons()).resolves.toBe(false)
  await expect(ensureFileTypeIcons()).resolves.toBe(true)
  expect(addCollection).toHaveBeenCalledTimes(2)
})
it('allows a later attempt after a dynamic import rejection', async () => {
  vi.doMock('@iconify-json/vscode-icons/icons.json', () => { throw new Error('chunk unavailable') })
  const { ensureFileTypeIcons } = await import('./fileTypeIcon')
  await expect(ensureFileTypeIcons()).resolves.toBe(false)
  expect(addCollection).not.toHaveBeenCalled()
  vi.doMock('@iconify-json/vscode-icons/icons.json', () => ({ default: { prefix: 'vscode-icons', icons: {} } }))
  addCollection.mockReturnValue(true)
  await expect(ensureFileTypeIcons()).resolves.toBe(true)
})
