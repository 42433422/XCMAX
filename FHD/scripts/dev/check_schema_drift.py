#!/usr/bin/env python3
"""Run the canonical Alembic parity check on a disposable SQLite database.

Uses the same upgrade/check entry points and env.py as FHD Alembic SSOT CI.
Exit codes: 0 = no drift, 1 = drift, 2 = migration/check execution failed.
"""

from __future__ import annotations

import argparse
import logging
import os
import shutil
import sys
import tempfile
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[2]  # FHD/
sys.path.insert(0, str(REPO_ROOT))

from app.utils.operational_errors import BOUNDARY_ERRORS


def _check_temp_db(db_url: str) -> str | None:
    from alembic.config import Config
    from alembic.util.exc import AutogenerateDiffsDetected

    from alembic import command

    cfg = Config(str(REPO_ROOT / "alembic.ini"))
    cfg.set_main_option("script_location", str(REPO_ROOT / "alembic"))
    previous_url = os.environ.get("DATABASE_URL")
    os.environ["DATABASE_URL"] = db_url
    try:
        command.upgrade(cfg, "head")
        logging.getLogger("alembic").setLevel(logging.WARNING)
        try:
            command.check(cfg)
        except AutogenerateDiffsDetected as exc:
            return str(exc)
        return None
    finally:
        if previous_url is None:
            os.environ.pop("DATABASE_URL", None)
        else:
            os.environ["DATABASE_URL"] = previous_url


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--keep-db", action="store_true", help="保留临时库便于排查")
    args = parser.parse_args()
    logging.getLogger("alembic").setLevel(logging.WARNING)
    tmpdir = tempfile.mkdtemp(prefix="xcagi_schema_drift_")
    db_url = f"sqlite:///{tmpdir}/drift.db"
    try:
        drift = _check_temp_db(db_url)
    except BOUNDARY_ERRORS as exc:
        print(f"[schema-drift] 门禁执行失败（非漂移结论）: {exc}")
        return 2
    finally:
        if args.keep_db:
            print(f"[schema-drift] 临时库保留于: {tmpdir}")
        else:
            shutil.rmtree(tmpdir, ignore_errors=True)
    if drift is not None:
        print(f"[schema-drift] FAIL：模型与迁移链漂移：{drift}")
        return 1
    print("[schema-drift] PASS：模型 metadata 与迁移链 schema 一致，无漂移。")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
