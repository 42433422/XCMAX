"""Fail-closed tests for the optional *real PostgreSQL* query-budget evidence tool.

These unit tests prove the guard, not database performance. The 1k/10k
evidence is only generated by the CLI against authorized existing PG rows.
"""

from __future__ import annotations

import argparse
import importlib.util
from pathlib import Path

import pytest

SCRIPT = Path(__file__).resolve().parents[2] / "scripts/dev/pg_customer_delete_read_budget.py"


def load():
    spec = importlib.util.spec_from_file_location("pg_customer_delete_read_budget", SCRIPT)
    assert spec is not None and spec.loader is not None
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def args():
    return argparse.Namespace(
        dsn_env="XCAGI_PG_BUDGET_DSN",
        tenant_id=7,
        head_sha="a" * 40,
        runs=20,
        max_sql=10,
        max_p95_ms=1500,
    )


def test_missing_real_postgres_dsn_is_blocked(monkeypatch):
    module = load()
    monkeypatch.delenv("XCAGI_PG_BUDGET_DSN", raising=False)
    with pytest.raises(module.EvidenceBlocked, match="DSN.*missing"):
        module.run(args())


def test_sqlite_cannot_generate_postgresql_business_evidence(monkeypatch):
    module = load()
    monkeypatch.setenv("XCAGI_PG_BUDGET_DSN", "sqlite://")
    with pytest.raises(module.EvidenceBlocked, match="not a PostgreSQL"):
        module.run(args())


@pytest.mark.parametrize(
    "head,tenant,runs,max_sql,max_p95",
    [
        ("not-a-sha", 7, 20, 10, 1500),
        ("a" * 40, 0, 20, 10, 1500),
        ("a" * 40, 7, 1, 10, 1500),
        ("a" * 40, 7, 20, 0, 1500),
        ("a" * 40, 7, 20, 10, 0),
    ],
)
def test_missing_evidence_scope_and_budgets_fail_closed(
    head, tenant, runs, max_sql, max_p95
):
    module = load()
    a = args()
    a.head_sha = head
    a.tenant_id = tenant
    a.runs = runs
    a.max_sql = max_sql
    a.max_p95_ms = max_p95
    with pytest.raises(module.EvidenceBlocked):
        module.run(a)


def test_nearest_rank_p95_does_not_understate_slowest_samples():
    module = load()
    assert module._p95(list(range(1, 21))) == 19
    assert module._p95([2.0, 3.0]) == 3.0


def test_explain_requires_postgres_json_plan():
    module = load()
    with pytest.raises(module.EvidenceBlocked, match="incomplete"):
        module._summarize_plan([{"no_plan": True}])
    assert module._summarize_plan(
        [{"Plan": {"Node Type": "Aggregate", "Total Cost": 12.5,
                   "Plan Rows": 1, "Plans": [
                       {"Node Type": "Index Scan", "Index Name": "idx_tenant"}
                   ]}}]
    ) == {
        "node": "Aggregate",
        "estimated_cost": 12.5,
        "estimated_rows": 1,
        "indexes": ["idx_tenant"],
    }


def test_report_sha_must_match_checked_out_git_commit(monkeypatch):
    from types import SimpleNamespace

    module = load()
    monkeypatch.setattr(
        module.subprocess,
        "run",
        lambda *args, **kwargs: SimpleNamespace(
            returncode=0, stdout="b" * 40,
        ),
    )
    with pytest.raises(module.EvidenceBlocked, match="actual checkout HEAD"):
        module._verify_checkout_head("a" * 40)
    module._verify_checkout_head("b" * 40)


def test_checkout_identity_unavailable_is_blocked(monkeypatch):
    module = load()

    def no_git(*_args, **_kwargs):
        raise FileNotFoundError("git")

    monkeypatch.setattr(module.subprocess, "run", no_git)
    with pytest.raises(module.EvidenceBlocked, match="SHA unavailable"):
        module._verify_checkout_head("a" * 40)


def test_pg_report_preserves_latency_and_sql_count_samples(monkeypatch):
    from types import SimpleNamespace

    module = load()
    a = args()
    a.runs = 2
    a.max_sql = 5
    a.max_p95_ms = 100.0
    class FakeConnect:
        def __enter__(self):
            return mock_connection

        def __exit__(self, *_args):
            return None

    mock_connection = SimpleNamespace(
        exec_driver_sql=lambda _sql: SimpleNamespace(
            scalar_one=lambda: "16.2",
        ),
    )
    fake_engine = SimpleNamespace(
        dialect=SimpleNamespace(name="postgresql"),
        connect=lambda: FakeConnect(),
        dispose=lambda: None,
    )
    monkeypatch.setenv(a.dsn_env, "postgresql://test-only-do-not-connect")
    monkeypatch.setattr(module, "create_engine", lambda *_args, **_kwargs: fake_engine)
    monkeypatch.setattr(module, "_verify_checkout_head", lambda expected: None)
    monkeypatch.setattr(module, "_samples", lambda *_args: {
        1000: [1] * 1000,
        10000: [2] * 10000,
    })
    invocations = []

    def fake_probe(_engine, _tenant, ids):
        invocations.append(len(ids))
        return {
            "elapsed_ms": float(len(invocations) * 10),
            "sql_total": 4,
            "sql_selects": 4,
            "denied_association_count": 1,
            "plans": {"query_1_customers": {"node": "Index Scan"}},
        }

    monkeypatch.setattr(module, "_probe", fake_probe)
    report = module.run(a)
    assert invocations == [1000, 1000, 10000, 10000]
    assert report["status"] == "PASS"
    assert report["head_sha"] == a.head_sha
    assert report["groups"][0]["latency_samples_ms"] == [10.0, 20.0]
    assert report["groups"][1]["sql_count_samples"] == [4, 4]
    assert report["groups"][1]["p95_ms"] == 40.0
