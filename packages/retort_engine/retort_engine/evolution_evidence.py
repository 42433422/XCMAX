"""Run frozen independent checks in two checkouts and retain raw evidence."""

from __future__ import annotations

import argparse
import hashlib
import json
import os
import subprocess
import tempfile
from pathlib import Path
from typing import Any
from uuid import uuid4

from retort_engine.evolution_contract import digest, safe_relative


def run_comparison(
    protocol: dict[str, Any],
    *,
    before: Path,
    after: Path,
    output: Path,
    run_id: str,
    target_sha: str,
    isolation: str = "docker",
) -> dict[str, Any]:
    frozen = {k: v for k, v in protocol.items() if k != "protocol_digest"}
    if digest(frozen) != protocol.get("protocol_digest"):
        raise ValueError("frozen audit protocol was modified")
    if isolation not in {"docker", "local_test"} or (
        isolation == "docker" and not protocol.get("container_image")
    ):
        raise ValueError("cloud verification requires a digest-pinned test image")
    for project, revision in ((before, protocol["source_sha"]), (after, target_sha)):
        head = subprocess.run(
            ["git", "rev-parse", "HEAD"],
            cwd=project,
            capture_output=True,
            text=True,
            check=True,
        ).stdout.strip()
        dirty = subprocess.run(
            ["git", "status", "--porcelain", "--untracked-files=no"],
            cwd=project,
            capture_output=True,
            text=True,
            check=True,
        ).stdout
        if head != revision or dirty:
            raise ValueError("independent checks require exact clean commits")
    output.mkdir(parents=True, exist_ok=True)
    result = {
        "schema_version": 1,
        "request_id": protocol["request_id"],
        "protocol_digest": protocol["protocol_digest"],
        "repository": protocol["repository"],
        "source_sha": protocol["source_sha"],
        "target_sha": target_sha,
        "run_id": str(run_id),
        "run_attempt": 1,
        "isolation": isolation,
        "checks": [],
    }
    for check in protocol["checks"]:
        row = {"id": check["id"], "check_digest": digest(check)}
        for phase, project in (("before", before), ("after", after)):
            _check_test_files(project, check["files"])
            relative = f"{check['id']}-{phase}.log"
            path = output / relative
            # Read the original protocol, not instructions generated by the code
            # under evaluation. Shell expansion is deliberately not involved.
            code, timed_out = execute_check(
                check,
                project,
                path,
                protocol.get("container_image") if isolation == "docker" else None,
            )
            _check_test_files(project, check["files"])
            row[phase] = {
                "returncode": code,
                "timed_out": timed_out,
                "log_path": relative,
                "log_sha256": hashlib.sha256(path.read_bytes()).hexdigest(),
            }
        result["checks"].append(row)
    (output / "verification.json").write_text(
        json.dumps(result, ensure_ascii=False, indent=2) + "\n"
    )
    return result


def execute_check(check, project, log, container_image=None, input_data=None):
    """Docker isolates evaluated code from the verifier, credentials and evidence."""
    import signal

    name = "retort-" + uuid4().hex
    env = {
        k: os.environ[k]
        for k in ("PATH", "SYSTEMROOT", "LANG", "TMPDIR")
        if k in os.environ
    }
    timed_out = False
    with (
        tempfile.TemporaryDirectory(prefix="retort-check-home-") as home,
        log.open("wb") as stream,
    ):
        env.update(HOME=home, PYTHONDONTWRITEBYTECODE="1")
        argv = check["argv"]
        if container_image:
            argv = [
                "docker",
                "run",
                "-i",
                "--rm",
                "--name",
                name,
                "--network",
                "none",
                "--read-only",
                "--cap-drop",
                "ALL",
                "--security-opt",
                "no-new-privileges",
                "--pids-limit",
                "256",
                "--memory",
                "4g",
                "--cpus",
                "2",
                "--user",
                f"{os.getuid()}:{os.getgid()}",
                "--tmpfs",
                "/tmp:rw,nosuid,nodev,size=512m",
                "-e",
                "HOME=/tmp",
                "-e",
                "PYTHONDONTWRITEBYTECODE=1",
                "--mount",
                f"type=bind,src={project.resolve()},dst=/workspace,readonly",
                "--workdir",
                "/workspace",
                "--entrypoint",
                argv[0],
                container_image,
                *argv[1:],
            ]
        process = subprocess.Popen(
            argv,
            cwd=project,
            env=env,
            stdout=stream,
            stderr=subprocess.STDOUT,
            stdin=subprocess.PIPE,
            start_new_session=True,
        )
        try:
            process.communicate(input=input_data, timeout=check["timeout_seconds"])
            code = process.returncode
        except subprocess.TimeoutExpired:
            timed_out = True
            code = -signal.SIGKILL
        finally:
            try:
                os.killpg(process.pid, signal.SIGKILL)
            except ProcessLookupError:
                pass
            process.wait()
            if container_image:
                subprocess.run(
                    ["docker", "rm", "-f", name],
                    check=False,
                    env=env,
                    capture_output=True,
                    timeout=30,
                )
    if log.stat().st_size > 8 * 1024 * 1024:
        raise ValueError("execution log exceeds evidence limit")
    return code, timed_out


def _check_test_files(project: Path, files: dict[str, str]) -> None:
    root = project.resolve()
    for relative, expected in files.items():
        path = root / safe_relative(relative)
        if (
            not path.is_file()
            or not path.resolve().is_relative_to(root)
            or path.is_symlink()
            or hashlib.sha256(path.read_bytes()).hexdigest() != expected
        ):
            raise ValueError(f"independent test/data changed: {relative}")


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    for name in ("protocol", "before", "after", "output", "run-id", "target-sha"):
        parser.add_argument(f"--{name}", required=True)
    args = parser.parse_args()
    result = run_comparison(
        json.loads(Path(args.protocol).read_text()),
        before=Path(args.before),
        after=Path(args.after),
        output=Path(args.output),
        run_id=args.run_id,
        target_sha=args.target_sha,
    )
    return int(
        any(
            row["after"]["returncode"] or row["after"]["timed_out"]
            for row in result["checks"]
        )
    )


if __name__ == "__main__":
    raise SystemExit(main())
