def _build_extension_policy_cases(target: int = 2600) -> list[tuple]:
    cases: list[tuple] = []
    # Always include raw extras first (odd path shapes)
    cases.extend(_EXTENSION_RAW_EXTRA)
    i = 0
    while len(cases) < target:
        prefix, ext, family, context, known, risk, kind = _EXTENSION_SEEDS[i % len(_EXTENSION_SEEDS)]
        n = i
        if kind == "nested":
            # prefix contains {n} placeholder directory
            path = prefix.format(n=f"{n:04d}") + f"/case_{n:04d}.{ext}"
        else:
            path = f"{prefix}/case_{n:04d}.{ext}"
        cases.append((path, family, context, known, risk))
        i += 1
    return cases


def _build_static_analysis_cases(target: int = 900) -> list[tuple]:
    cases: list[tuple] = []
    i = 0
    while len(cases) < target:
        prefix, suffix, line, rule, status, hi, med = _STATIC_SEEDS[i % len(_STATIC_SEEDS)]
        if suffix:
            path = f"{prefix}{i:04d}{suffix}"
        else:
            path = prefix
        cases.append((path, line, rule, status, hi, med))
        i += 1
    return cases


