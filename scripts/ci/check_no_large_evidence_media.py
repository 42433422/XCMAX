#!/usr/bin/env python3
"""Fail if forbidden evidence/promo media re-enters the tracked tree.

Coexists with #2544 evidence-materialization: FHD/docs/evidence originals listed
in the materialization manifest may remain tracked. Generated capability-center
public copies, appstore/promo binaries, and unregistered FHD evidence media must
not be tracked.
"""
from __future__ import annotations

import json
import os
import subprocess
import sys
from pathlib import Path

MEDIA_EXT = {
    ".png", ".jpg", ".jpeg", ".gif", ".webp",
    ".mp4", ".webm", ".mov", ".mkv",
}
FORBIDDEN_PREFIXES = (
    "成都修茈科技有限公司/capabilities/assets/evidence/",
    "appstore-screenshots/",
    "宣传资料/",
)
MARKETING_PREFIXES = (
    "成都修茈科技有限公司/public/",
    "成都修茈科技有限公司/marketing-assets/",
)
MAX_MARKETING_BYTES = 512 * 1024
MANIFEST = "成都修茈科技有限公司/data/capabilities/evidence-materialization.json"



def materialization_retained(root: Path) -> set[str]:
    path = root / MANIFEST
    if not path.is_file():
        return set()
    data = json.loads(path.read_text(encoding="utf-8"))
    return set(data.get("retained_sources", {}))



def media_alias_sources(root: Path) -> set[str]:
    path = root / "config/media-aliases.json"
    if not path.is_file():
        return set()
    data = json.loads(path.read_text(encoding="utf-8"))
    return {entry["source"] for entry in data.get("aliases", {}).values()}


def materialization_sources(root: Path) -> set[str]:
    path = root / MANIFEST
    if not path.is_file():
        return set()
    data = json.loads(path.read_text(encoding="utf-8"))
    out: set[str] = set()
    for section in ("assets", "retained_sources", "source_aliases"):
        for entry in data.get(section, {}).values():
            out.add(entry["source"])
    return out


def main() -> int:
    root = Path(
        subprocess.check_output(["git", "rev-parse", "--show-toplevel"], text=True).strip()
    )
    os.chdir(root)
    allowed = materialization_sources(root)
    media_sources = media_alias_sources(root)
    out = subprocess.check_output(["git", "ls-tree", "-r", "-l", "HEAD"], text=True)
    bad: list[str] = []
    for line in out.splitlines():
        try:
            meta, path = line.split("\t", 1)
        except ValueError:
            continue
        parts = meta.split()
        if len(parts) < 4 or parts[1] != "blob":
            continue
        size = int(parts[3])
        ext = os.path.splitext(path)[1].lower()
        if ext not in MEDIA_EXT:
            continue
        if any(path == p or path.startswith(p) for p in FORBIDDEN_PREFIXES):
            retained = materialization_retained(root)
            base = path.rsplit("/", 1)[-1]
            if path.startswith("成都修茈科技有限公司/capabilities/assets/evidence/") and base in retained:
                continue
            if path in media_sources:
                continue
            if path.startswith("appstore-screenshots/2.3.3-accurate-metadata/"):
                continue
            bad.append(f"{size}\t{path}  (generated/public or promo path)")
            continue
        if path.startswith("FHD/docs/evidence/") and path not in allowed:
            bad.append(f"{size}\t{path}  (not in evidence-materialization.json)")
            continue
        if any(path.startswith(p) for p in MARKETING_PREFIXES) and size > MAX_MARKETING_BYTES:
            bad.append(f"{size}\t{path}  (> {MAX_MARKETING_BYTES} marketing media)")
    if bad:
        print("check_no_large_evidence_media: FAIL")
        for row in bad[:50]:
            print(" ", row)
        if len(bad) > 50:
            print(f"  ... and {len(bad) - 50} more")
        print(
            "Offload unregistered media to ~/XCMAX-archives/evidence-bulk-*; "
            "keep ARCHIVE_POINTER.md; public capability copies are generated by "
            "evidence_assets.materialize (do not track)."
        )
        return 1
    print("check_no_large_evidence_media: OK")
    return 0


if __name__ == "__main__":
    sys.exit(main())
